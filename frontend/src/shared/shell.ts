/*
  把一段文本变成「塞进终端后仍然是一个字面量」的形式。

  **判据必须是白名单，不能是黑名单。** 原来 `quoteShellPath` 列的是「遇到这些字符才引用」，
  而那张表漏了 `( ) ; & | < > * ? [ ] { } ~ #` 等一大批。实测后果：

      a(b).ts   → 原样输出，bash 直接语法错误
      x;id.ts   → 原样输出，`;` 当命令分隔符，`id` 真的会执行
      a&b.ts    → 原样输出，`&` 把前半段丢后台、后半段当命令跑

  而 roost 在公网上、又有文件上传：传一个叫 `x;curl …|sh.txt` 的文件，再从文件树拖进终端，
  那段就跑了。黑名单的问题不在于这次漏了哪几个——是它下次还会漏，而漏了不会有任何征兆。
  白名单反过来：不认识的字符一律引用，最坏结果只是多几个引号。

  **用单引号，不是双引号。** 双引号里 `$VAR` 和 `` `cmd` `` 仍然会展开，所以原来那一版还得
  再转义一轮；单引号里除了单引号本身没有任何东西有特殊含义，只需要处理一种情况。
*/

/**
 * POSIX 单引号引用：任何字符串都能安全地当成**一个**参数。
 *
 * 单引号里唯一需要处理的是单引号自己，办法是 `'` → `'"'"'`（收尾、用双引号包一个字面
 * 单引号、再开头）。空串会变成 `''`，那正是「一个空参数」的正确写法。
 */
export const shellQuote = (value: string): string => `'${value.replace(/'/g, `'"'"'`)}'`;

/**
 * 不需要引用的形状。
 *
 * 只收 ASCII 里确定无特殊含义的那些字符。**非 ASCII 一律引用**——它们在 shell 里虽然也
 * 不是元字符，但把「中文文件名」放进白名单意味着要判断哪些 Unicode 码位是安全的，
 * 而那是个没有尽头的问题；多打一对引号则没有任何代价。
 */
const UNQUOTED = /^[A-Za-z0-9._/@:+,%=-]+$/;

/**
 * 路径要插进终端时的形式。
 *
 * 形状足够普通就原样给出（终端里读起来干净），否则单引号包起来。
 *
 * **`~` 整个排除在白名单外，不只是开头。** 波浪号展开确实主要发生在词首，但在 `:` 后面
 * 也会（`PATH=a:~/b` 那一类），而白名单里恰好有 `:`。与其去分辨哪些位置安全，不如让任何
 * 含 `~` 的路径都走引用——它出现在文件名里本来就少见。
 *
 * 开头的 `-` 另外挡一道：它不是元字符，但会被后面那个命令当成选项，那不是「这是一个
 * 文件名」的意思。
 */
export function quoteShellPath(path: string): string {
  return UNQUOTED.test(path) && !path.startsWith("-") ? path : shellQuote(path);
}
