/**
 * 「这块屏幕窄到一次只能放一段内容吗」。
 *
 * **抽成纯函数是为了能测**：断点这种数字一旦只活在组件里，就只能靠截图去验，而截图验不了
 * 边界值。判据本身只有一行，值得的是那个值和它的理由。
 */
export const NARROW_LAYOUT_MAX = 820;

/*
  820 是这么来的：骨架是两条 40 像素图标栏 + 三个面板。要让左右任意一个面板还剩 300 像素
  可用（文件名、会话标题在这个宽度才不至于全是省略号），中间又至少留一屏终端，加起来就落在
  这个数附近。[实测] 390 像素的手机上不收起侧栏，面板标题会被截成 `W...`、`F...`。

  **刻意不看 `pointer: coarse`**：这是个宽度问题，不是输入方式问题。iPad 横屏是触屏但宽得很，
  而一个窄窗口的桌面浏览器不是触屏却一样挤。把两者混为一谈，两边都会判错。
*/
export function isNarrowLayout(width: number): boolean {
  return width <= NARROW_LAYOUT_MAX;
}
